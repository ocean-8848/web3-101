<p>速算额推导：档位 k 的速算额 = 档位 k−1 的速算额 + 档位边界 × (MMR<sub>k</sub> − MMR<sub>k−1</sub>)。验证档 2/3 边界 250,000：档 2 维持保证金 = 250,000 × 0.5% − 50 = 1,200；档 3 = 250,000 × 1% − 1,300 = 1,200。连续。</p>

